"""Import baked Epic sample motions onto Wildline's existing hunter skeleton."""
import json
import math
from pathlib import Path
import unreal as ue

root = Path(ue.Paths.project_dir()).resolve()
source = root / 'ArtSource/Hunters/GameAnimationSample'
motions = json.loads((source / 'motions.json').read_text())
eal = ue.EditorAssetLibrary
base = '/Game/Wildline/Hunters/Animations'
skeleton = ue.load_asset('/Game/Characters/Mannequins/Meshes/SK_Mannequin')
assert skeleton
world = ue.get_editor_subsystem(ue.UnrealEditorSubsystem).get_editor_world()
ue.SystemLibrary.execute_console_command(world, 'Interchange.FeatureFlags.Import.FBX 0')
options = ue.FbxImportUI()
options.automated_import_should_detect_type = False
options.mesh_type_to_import = ue.FBXImportType.FBXIT_ANIMATION
options.import_as_skeletal = True
options.import_mesh = False
options.import_animations = True
options.import_materials = False
options.import_textures = False
options.skeleton = skeleton
options.anim_sequence_import_data.set_editor_property('use_default_sample_rate', True)
options.anim_sequence_import_data.set_editor_property('import_custom_attribute', False)
options.anim_sequence_import_data.set_editor_property('remove_redundant_keys', True)
options.anim_sequence_import_data.set_editor_property('animation_length', ue.FBXAnimationLengthImportType.FBXALIT_EXPORTED_TIME)
tasks = []
for item in motions:
    task = ue.AssetImportTask()
    task.factory = ue.FbxFactory()
    task.filename = str(source / 'Export' / (item['name'] + '.fbx'))
    task.destination_path = base
    task.destination_name = item['name']
    task.options = options
    task.automated = True
    task.replace_existing = True
    task.replace_existing_settings = True
    task.save = True
    tasks.append(task)
ue.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)

for item in motions:
    a = ue.load_asset(base + '/' + item['name'])
    assert a, item['name']
    assert a.get_editor_property('skeleton') == skeleton
    a.set_editor_property('enable_root_motion', False)
    a.set_editor_property('force_root_lock', False)
    length = a.sequence_length
    samples = [ue.AnimationLibrary.get_bone_pose_for_time(a, 'root', i / 30, False) for i in range(round(length * 30) + 1)]
    velocities = [(b.translation - a.translation) * 30 for a, b in zip(samples, samples[1:])]
    speeds = [math.hypot(v.x, v.y) for v in velocities]
    start, end = 0, min(length, .65)
    if 'Start_' in item['name']:
        begin = next((i for i, v in enumerate(speeds) if v > 20), 0)
        peak = max(speeds)
        finish = next((i for i in range(begin + 1, len(speeds)) if speeds[i] > peak * .9), min(len(speeds)-1, begin+18))
        start = max(0, (begin - 2) / 30)
        end = max(start + .25, (finish + 3) / 30)
    elif 'Stop_' in item['name']:
        peak = max(speeds)
        slow = next((i for i, v in enumerate(speeds) if v < peak * .8), 0)
        finish = next((i for i in range(slow, len(speeds)) if speeds[i] < 12), len(speeds)-1)
        start = max(0, (slow - 2) / 30)
        end = min(length, max(start + .3, (finish + 5) / 30))
    elif 'Turn' in item['name']:
        initial = samples[0].rotation.rotator().yaw
        changed = [i for i, p in enumerate(samples) if abs(ue.MathLibrary.normalized_delta_rotator(p.rotation.rotator(), samples[0].rotation.rotator()).yaw) > 3]
        start = max(0, (changed[0] - 2) / 30) if changed else .2
        end = min(length, start + .9)
    elif item['name'].endswith('JumpStart'):
        begin = next((i for i, v in enumerate(velocities) if v.z > 20), 0)
        start = max(0, begin / 30)
        end = min(length, start + .4)
    elif item['name'].endswith('Land'):
        falling = next((i for i, v in enumerate(velocities) if v.z < -20), 0)
        settle = next((i for i in range(falling+1, len(velocities)) if abs(velocities[i].z) < 12), falling+15)
        start = max(0, (settle - 3) / 30)
        end = min(length, start + .4)
    item['active_start'] = start
    item['active_duration'] = max(.2, end-start)
    if 'period' in item:
        cycles = max(1, round(item['length'] / item['period']))
        item['period'] = length / cycles
        item['stride'] = item['distance'] / cycles
    a.set_editor_property('force_root_lock', True)
    a.set_editor_property('root_motion_root_lock', ue.RootMotionRootLock.REF_POSE)
    eal.save_loaded_asset(a)
    ue.log('HUNTER MOTION IMPORT ' + json.dumps(item))

# Generated timing describes the actual capture, rather than guessed cadence.
lookup = {m['name']: m for m in motions}
labels = ['Fwd', 'FwdRight', 'Right', 'BwdRight', 'Bwd', 'BwdLeft', 'Left', 'FwdLeft']
lines = ['#pragma once', '// Generated by Scripts/import_hunter_motion.py from Epic capture data.',
         'namespace WildlineMotion {', 'struct FGait { float Period, Offset, Stride; };',
         'struct FTransition { float Start, Duration; };']
for gait in ['Walk', 'Run', 'Crouch']:
    values = [lookup['A_Hunter_' + gait + '_' + label] for label in labels]
    lines += ['inline constexpr FGait ' + gait + '[8] = {']
    lines += ['    {%.6ff, %.6ff, %.6ff},' % (m['period'], m['offset'], m['stride']) for m in values]
    lines += ['};']
for gait in ['WalkStart', 'WalkStop', 'RunStart', 'RunStop']:
    lines += ['inline constexpr FTransition ' + gait + '[8] = {']
    for label in labels:
        m = lookup['A_Hunter_' + gait + '_' + label]
        lines += ['    {%.6ff, %.6ff},' % (m['active_start'], m['active_duration'])]
    lines += ['};']
for name in ['TurnLeft', 'TurnRight', 'JumpStart', 'Land']:
    m = lookup['A_Hunter_' + name]
    lines += ['inline constexpr FTransition ' + name + ' = {%.6ff, %.6ff};' % (m['active_start'], m['active_duration'])]
lines += ['}']
(root / 'Source/Wildline/WildlineHunterMotionData.h').write_text('\n'.join(lines) + '\n')
(source / 'imported-motions.json').write_text(json.dumps(motions, indent=2))
ue.log('HUNTER MOTION IMPORT COMPLETE ' + str(len(motions)))
